alter table public.timesheets add column if not exists leave_snapshot jsonb not null default '[]'::jsonb;

create table if not exists public.workflow_events (
    id bigint generated by default as identity primary key,
    kind text not null check (kind in ('timesheets','leave_requests','entitlement')),
    document_id bigint not null,
    user_id bigint not null references public.users(id),
    actor_user_id bigint references public.users(id),
    action text not null,
    status text not null,
    comment text not null default '',
    created_at text not null
);
create index if not exists workflow_events_document_idx on public.workflow_events(kind, document_id, id);
alter table public.workflow_events enable row level security;
revoke all on table public.workflow_events from anon, authenticated;
grant select, insert on table public.workflow_events to service_role;
grant usage on sequence public.workflow_events_id_seq to service_role;
create or replace function public.prevent_workflow_event_mutation()
returns trigger language plpgsql security invoker set search_path = public, pg_temp as $$
begin
    raise exception 'Workflow history is immutable';
end;
$$;
drop trigger if exists workflow_events_immutable on public.workflow_events;
create trigger workflow_events_immutable before update or delete on public.workflow_events
    for each row execute function public.prevent_workflow_event_mutation();
drop trigger if exists workflow_events_no_truncate on public.workflow_events;
create trigger workflow_events_no_truncate before truncate on public.workflow_events
    for each statement execute function public.prevent_workflow_event_mutation();

-- Callers lock the user's row first. Every reservation, decision, and allowance
-- update for one person shares that lock, including previously absent periods.
create or replace function public.assert_leave_reservation(
    p_user bigint, p_start date, p_end date, p_type text,
    p_holidays jsonb, p_exclude bigint default null
) returns void language plpgsql security invoker set search_path = public, pg_temp as $$
declare
    allowance record;
    reserved integer;
begin
    if p_type not in ('Vacation', 'Unpaid', 'Other') or p_end < p_start or p_end - p_start > 366 then
        raise exception 'WORKFLOW_CONFLICT: Choose a valid leave range and type.';
    end if;
    if p_type = 'Vacation' and not exists (
        select 1 from generate_series(p_start::timestamp, p_end::timestamp, '1 day') d
        where extract(isodow from d) < 6 and not p_holidays ? to_char(d, 'YYYY-MM-DD')
    ) then
        raise exception 'WORKFLOW_CONFLICT: Annual leave must include at least one working day.';
    end if;
    if exists (
        select 1 from public.leave_requests where user_id = p_user
        and status in ('submitted', 'accepted') and id is distinct from p_exclude
        and start_date::date <= p_end and end_date::date >= p_start
    ) then
        raise exception 'WORKFLOW_CONFLICT: These dates overlap one of your existing requests.';
    end if;
    if p_type <> 'Vacation' then return; end if;
    for allowance in select year, days from public.leave_entitlements
        where user_id = p_user and year between extract(year from p_start) and extract(year from p_end)
    loop
        select count(distinct d::date) into reserved from (
            select p_start as first_day, p_end as last_day
            union all
            select start_date::date, end_date::date from public.leave_requests
            where user_id = p_user and status in ('submitted', 'accepted')
                and leave_type = 'Vacation' and id is distinct from p_exclude
                and start_date::date <= make_date(allowance.year, 12, 31)
                and end_date::date >= make_date(allowance.year, 1, 1)
        ) ranges cross join lateral generate_series(
            greatest(first_day, make_date(allowance.year, 1, 1))::timestamp,
            least(last_day, make_date(allowance.year, 12, 31))::timestamp, '1 day') d
        where extract(isodow from d) < 6 and not p_holidays ? to_char(d, 'YYYY-MM-DD');
        if reserved > allowance.days then
            raise exception 'WORKFLOW_CONFLICT: Annual leave exceeds the available allowance for %.', allowance.year;
        end if;
    end loop;
end;
$$;

create or replace function public.submit_timesheet_atomic(p_values jsonb)
returns jsonb language plpgsql security invoker set search_path = public, pg_temp as $$
declare
    saved public.timesheets;
    person bigint := (p_values->>'user_id')::bigint;
    current_leave jsonb;
    expected_leave jsonb;
    resubmitting boolean;
begin
    perform 1 from public.users where id = person for update;
    if not found then raise exception 'WORKFLOW_CONFLICT: Employee no longer exists.'; end if;
    select * into saved from public.timesheets where user_id = person
        and year = (p_values->>'year')::integer and month = (p_values->>'month')::integer for update;
    if found and saved.status <> 'needs_changes' then
        raise exception 'WORKFLOW_CONFLICT: This month is already submitted or approved. Refresh before continuing.';
    end if;
    resubmitting := saved.id is not null;
    if coalesce((p_values->>'validate_leave_snapshot')::boolean, false) then
        select coalesce(jsonb_agg(jsonb_build_object('id', id, 'start_date', start_date,
            'end_date', end_date, 'leave_type', leave_type) order by id), '[]'::jsonb)
        into current_leave from public.leave_requests where user_id = person and status = 'accepted'
            and start_date::date < (make_date((p_values->>'year')::integer, (p_values->>'month')::integer, 1) + interval '1 month')::date
            and end_date::date >= make_date((p_values->>'year')::integer, (p_values->>'month')::integer, 1);
        select coalesce(jsonb_agg(item order by (item->>'id')::bigint), '[]'::jsonb)
            into expected_leave from jsonb_array_elements(p_values->'leave_snapshot') item;
        if current_leave <> expected_leave then
            raise exception 'WORKFLOW_CONFLICT: Approved leave changed while this document was generated. Refresh and submit again.';
        end if;
    end if;
    insert into public.timesheets(user_id, year, month, format, vacation, sick,
        custom_days, custom_reason, working_days, total_hours, filename, storage_key,
        leave_snapshot, submitted_at, status, review_comment, reviewed_at)
    values(person, (p_values->>'year')::integer, (p_values->>'month')::integer,
        p_values->>'format', p_values->>'vacation', p_values->>'sick',
        p_values->>'custom_days', p_values->>'custom_reason',
        (p_values->>'working_days')::integer, (p_values->>'total_hours')::numeric,
        p_values->>'filename', p_values->>'storage_key', coalesce(p_values->'leave_snapshot','[]'::jsonb),
        p_values->>'submitted_at', 'submitted', '', null)
    on conflict(user_id, year, month) do update set
        format = excluded.format, vacation = excluded.vacation, sick = excluded.sick,
        custom_days = excluded.custom_days, custom_reason = excluded.custom_reason,
        working_days = excluded.working_days, total_hours = excluded.total_hours,
        filename = excluded.filename, storage_key = excluded.storage_key,
        leave_snapshot = excluded.leave_snapshot, submitted_at = excluded.submitted_at,
        status = 'submitted', review_comment = '', reviewed_at = null
    returning * into saved;
    insert into public.workflow_events(kind, document_id, user_id, actor_user_id, action, status, comment, created_at)
    values('timesheets', saved.id, person, (p_values->>'actor_user_id')::bigint,
        case when resubmitting then 'resubmitted' else 'submitted' end, 'submitted', '', p_values->>'submitted_at');
    return to_jsonb(saved);
end;
$$;

create or replace function public.submit_leave_atomic(p_values jsonb, p_holidays jsonb)
returns jsonb language plpgsql security invoker set search_path = public, pg_temp as $$
declare
    saved public.leave_requests;
    person bigint := (p_values->>'user_id')::bigint;
begin
    perform 1 from public.users where id = person for update;
    if not found then raise exception 'WORKFLOW_CONFLICT: Employee no longer exists.'; end if;
    perform public.assert_leave_reservation(person, (p_values->>'start_date')::date,
        (p_values->>'end_date')::date, p_values->>'leave_type', p_holidays);
    insert into public.leave_requests(user_id, start_date, end_date, leave_type,
        comment, filename, storage_key, submitted_at)
    values(person, p_values->>'start_date', p_values->>'end_date', p_values->>'leave_type',
        p_values->>'comment', p_values->>'filename', p_values->>'storage_key', p_values->>'submitted_at')
    returning * into saved;
    insert into public.workflow_events(kind, document_id, user_id, actor_user_id, action, status, comment, created_at)
    values('leave_requests', saved.id, person, (p_values->>'actor_user_id')::bigint,
        'submitted', 'submitted', '', p_values->>'submitted_at');
    return to_jsonb(saved);
end;
$$;

create or replace function public.review_document_atomic(
    p_kind text, p_id bigint, p_status text, p_comment text, p_reviewed_at text,
    p_expected_submitted_at text default null, p_reopen boolean default false,
    p_holidays jsonb default '[]'::jsonb, p_actor_user_id bigint default null
) returns jsonb language plpgsql security invoker set search_path = public, pg_temp as $$
declare
    saved jsonb;
    person bigint;
    required_status text := case when p_reopen then 'accepted' else 'submitted' end;
begin
    if p_status not in ('accepted', 'needs_changes') or length(p_comment) > 1000
        or (p_status = 'needs_changes' and length(trim(p_comment)) = 0)
        or (p_reopen and (p_kind <> 'timesheets' or p_status <> 'needs_changes')) then
        raise exception 'WORKFLOW_CONFLICT: Choose a valid decision and provide a reason for changes.';
    end if;
    if p_kind = 'timesheets' then
        select user_id into person from public.timesheets where id = p_id;
    elsif p_kind = 'leave_requests' then
        select user_id into person from public.leave_requests where id = p_id;
    else
        raise exception 'WORKFLOW_CONFLICT: Unknown document type.';
    end if;
    if person is null then return null; end if;
    perform 1 from public.users where id = person for update;
    if p_kind = 'timesheets' then
        select to_jsonb(t) into saved from public.timesheets t where id = p_id for update;
    else
        select to_jsonb(l) into saved from public.leave_requests l where id = p_id for update;
    end if;
    if saved->>'status' <> required_status or (p_expected_submitted_at is not null
        and saved->>'submitted_at' <> p_expected_submitted_at) then
        raise exception 'WORKFLOW_CONFLICT: This request changed after you opened it. Refresh before reviewing it.';
    end if;
    if p_kind = 'leave_requests' and p_status = 'accepted' then
        perform public.assert_leave_reservation(person, (saved->>'start_date')::date,
            (saved->>'end_date')::date, saved->>'leave_type', p_holidays, p_id);
    end if;
    if p_kind = 'timesheets' then
        update public.timesheets set status = p_status, review_comment = trim(p_comment),
            reviewed_at = p_reviewed_at where id = p_id returning to_jsonb(timesheets) into saved;
    else
        update public.leave_requests set status = p_status, review_comment = trim(p_comment),
            reviewed_at = p_reviewed_at where id = p_id returning to_jsonb(leave_requests) into saved;
    end if;
    insert into public.workflow_events(kind, document_id, user_id, actor_user_id, action, status, comment, created_at)
    values(p_kind, p_id, person, p_actor_user_id, case when p_reopen then 'reopened' else 'reviewed' end,
        p_status, trim(p_comment), p_reviewed_at);
    return saved;
end;
$$;

create or replace function public.set_entitlement_atomic(p_values jsonb, p_holidays jsonb)
returns jsonb language plpgsql security invoker set search_path = public, pg_temp as $$
declare
    person bigint := (p_values->>'user_id')::bigint;
    selected_year integer := (p_values->>'year')::integer;
    allowance numeric := (p_values->>'days')::numeric;
    reserved integer;
begin
    perform 1 from public.users where id = person for update;
    if not found then raise exception 'WORKFLOW_CONFLICT: Employee no longer exists.'; end if;
    if allowance < 0 or allowance > 366 or allowance * 2 <> trunc(allowance * 2) then
        raise exception 'WORKFLOW_CONFLICT: Enter a valid annual allowance.';
    end if;
    select count(distinct d::date) into reserved from public.leave_requests l
    cross join lateral generate_series(
        greatest(l.start_date::date, make_date(selected_year, 1, 1))::timestamp,
        least(l.end_date::date, make_date(selected_year, 12, 31))::timestamp, '1 day') d
    where l.user_id = person and l.leave_type = 'Vacation' and l.status in ('submitted', 'accepted')
        and l.start_date::date <= make_date(selected_year, 12, 31) and l.end_date::date >= make_date(selected_year, 1, 1)
        and extract(isodow from d) < 6 and not p_holidays ? to_char(d, 'YYYY-MM-DD');
    if reserved > allowance then
        raise exception 'WORKFLOW_CONFLICT: The allowance cannot be lower than approved and pending annual leave.';
    end if;
    insert into public.leave_entitlements(user_id, year, days) values(person, selected_year, allowance)
        on conflict(user_id, year) do update set days = excluded.days;
    insert into public.workflow_events(kind, document_id, user_id, actor_user_id, action, status, comment, created_at)
    values('entitlement', selected_year, person, (p_values->>'actor_user_id')::bigint,
        'allowance_updated', 'updated', 'Annual allowance: ' || allowance || ' days',
        to_char(clock_timestamp() at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US') || '+00:00');
    return jsonb_build_object('user_id', person, 'year', selected_year, 'days', allowance);
end;
$$;

