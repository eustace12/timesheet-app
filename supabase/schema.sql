-- Timesheet Generator production schema.
-- Run this in the Supabase SQL Editor before deploying the application.
-- The application authenticates with SUPABASE_SERVICE_ROLE_KEY on the server only.
-- Never expose that key to a browser, and do not add public Storage policies.

create table if not exists public.users (
    id bigint generated by default as identity primary key,
    username text not null unique,
    password_hash text not null,
    full_name text not null,
    role text not null check (role in ('employee', 'admin')),
    company_name text not null default 'Urchin Systems SA',
    hours_per_day integer not null default 8,
    created_at text not null
);

create table if not exists public.timesheets (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id),
    year integer not null,
    month integer not null check (month between 1 and 12),
    format text not null check (format in ('pdf', 'xlsx')),
    vacation text not null default '',
    sick text not null default '',
    custom_days text not null default '',
    custom_reason text not null default '',
    working_days integer not null,
    total_hours integer not null,
    filename text not null,
    storage_key text,
    submitted_at text not null,
    status text not null default 'submitted'
        check (status in ('submitted', 'accepted', 'needs_changes')),
    review_comment text not null default '',
    reviewed_at text,
    unique (user_id, year, month)
);

create table if not exists public.leave_requests (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id),
    start_date text not null,
    end_date text not null,
    leave_type text not null,
    comment text not null default '',
    filename text not null,
    storage_key text,
    submitted_at text not null,
    status text not null default 'submitted'
        check (status in ('submitted', 'accepted', 'needs_changes')),
    review_comment text not null default '',
    reviewed_at text,
    check (end_date >= start_date)
);

-- The server uses SUPABASE_SERVICE_ROLE_KEY, which bypasses RLS. Browser roles
-- must never read personnel data, password hashes, requests, or storage keys.
alter table public.users enable row level security;
alter table public.timesheets enable row level security;
alter table public.leave_requests enable row level security;

revoke all on table public.users from anon, authenticated;
revoke all on table public.timesheets from anon, authenticated;
revoke all on table public.leave_requests from anon, authenticated;

create index if not exists timesheets_user_year_month_idx
    on public.timesheets (user_id, year, month);
create index if not exists leave_requests_user_dates_idx
    on public.leave_requests (user_id, start_date, end_date);

-- Private bucket for generated PDFs and XLSX files.
insert into storage.buckets (id, name, public)
values ('timesheet-documents', 'timesheet-documents', false)
on conflict (id) do nothing;

-- Profiles are managed in People (/admin/users), without application passwords.
-- The legacy password_hash column is retained for compatibility; it is unused.
