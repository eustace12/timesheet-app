-- Additive People-workspace migration. Apply after schema.sql.
-- Deployment bootstrap applies this only to the isolated People demo database.
create table if not exists public.time_entries (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id),
    work_date date not null,
    project text not null check (length(project) between 1 and 160),
    task text not null check (length(task) between 1 and 240),
    minutes integer not null check (minutes between 1 and 1440),
    billable integer not null default 0 check (billable in (0, 1)),
    notes text not null default '' check (length(notes) <= 2000),
    created_at text not null,
    updated_at text not null
);
create index if not exists time_entries_user_date_idx on public.time_entries(user_id, work_date);
create table if not exists public.leave_entitlements (
    user_id bigint not null references public.users(id),
    year integer not null check (year between 1 and 9999),
    days numeric(5,1) not null check (days between 0 and 366),
    primary key(user_id, year)
);
alter table public.timesheets alter column total_hours type numeric(12,6);
alter table public.time_entries enable row level security;
alter table public.leave_entitlements enable row level security;
revoke all on table public.time_entries, public.leave_entitlements from anon, authenticated;

create or replace function public.enforce_time_entry_rules()
returns trigger language plpgsql set search_path = public, pg_temp as $$
declare
    selected_user bigint;
    selected_day date;
    existing_minutes integer;
begin
    if TG_OP = 'DELETE' then
        selected_user := OLD.user_id;
        selected_day := OLD.work_date;
    else
        selected_user := NEW.user_id;
        selected_day := NEW.work_date;
    end if;
    -- Serialize day-total checks across concurrent API requests.
    perform pg_advisory_xact_lock(hashtextextended('time-entry:' || selected_user || ':' || selected_day, 0));
    -- Use the same row lock as approval updates, including when editing a draft.
    perform 1 from public.timesheets where user_id = selected_user
        and year = extract(year from selected_day) and month = extract(month from selected_day)
        for update;
    if exists(select 1 from public.timesheets where user_id = selected_user
        and year = extract(year from selected_day) and month = extract(month from selected_day)
        and status in ('submitted', 'accepted')) then
        raise exception 'Timesheet period is locked';
    end if;
    if TG_OP = 'UPDATE' then
        perform 1 from public.timesheets where user_id = OLD.user_id
            and year = extract(year from OLD.work_date) and month = extract(month from OLD.work_date)
            for update;
        if exists(select 1 from public.timesheets where user_id = OLD.user_id
            and year = extract(year from OLD.work_date) and month = extract(month from OLD.work_date)
            and status in ('submitted', 'accepted')) then
            raise exception 'Timesheet period is locked';
        end if;
    end if;
    if TG_OP <> 'DELETE' then
        if TG_OP = 'INSERT' then
            select coalesce(sum(minutes), 0) into existing_minutes from public.time_entries
                where user_id = NEW.user_id and work_date = NEW.work_date;
        else
            select coalesce(sum(minutes), 0) into existing_minutes from public.time_entries
                where user_id = NEW.user_id and work_date = NEW.work_date and id <> OLD.id;
        end if;
        if existing_minutes + NEW.minutes > 1440 then
            raise exception 'Daily total cannot exceed 24 hours';
        end if;
        if exists(select 1 from public.leave_requests where user_id = NEW.user_id
            and start_date <= NEW.work_date::text and end_date >= NEW.work_date::text
            and status = 'accepted') then
            raise exception 'This date has approved leave';
        end if;
    end if;
    if TG_OP = 'DELETE' then return OLD; end if;
    return NEW;
end;
$$;
drop trigger if exists time_entries_guard on public.time_entries;
create trigger time_entries_guard before insert or update or delete on public.time_entries
    for each row execute function public.enforce_time_entry_rules();
